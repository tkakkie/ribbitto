const synthetic = `package view
const (
 //dom:id HTMLFormElement
 Form = "form"
 //dom:suffix HTMLLIElement
 Item = "item-"
 //dom:attribute
 Value = "data-value"
 //dom:event ChangedDetail
 Changed = "changed"
)
type ChangedDetail struct { Key string ` + "`json:\"key,omitempty\"`" + `; Text string; Count int64; Ready bool; Ratio float64 }
`

func write(t *testing.T, path, text string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(text), 0600); err != nil {
		t.Fatal(err)
	}
}

func TestFreshness(t *testing.T) {
	root := t.TempDir()
	input, output := filepath.Join(root, "internal/web/view/contracts.go"), filepath.Join(root, "web/src/contracts.gen.ts")
	write(t, input, synthetic)
	write(t, filepath.Join(root, "web/src/.keep"), "")
	if err := run(root, true); err == nil {
		t.Fatal("accepted missing output")
	}
	if _, err := os.Stat(output); !os.IsNotExist(err) {
		t.Fatal("check wrote missing output")
	}
	if err := run(root, false); err != nil {
		t.Fatal(err)
	}
	fresh, err := os.ReadFile(output)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(fresh), "// Code generated by domcontract; DO NOT EDIT.\n") {
		t.Fatal("missing generated header")
	}
	if err := run(root, false); err != nil {
		t.Fatal(err)
	}
	again, err := os.ReadFile(output)
	if err != nil || string(again) != string(fresh) {
		t.Fatal("nondeterministic generation")
	}
	if err := run(root, true); err != nil {
		t.Fatal(err)
	}
	for _, change := range []string{"stale", "hand-edited"} {
		t.Run(change, func(t *testing.T) {
			write(t, input, synthetic)
			write(t, output, string(fresh))
			if change == "stale" {
				write(t, input, strings.ReplaceAll(synthetic, "data-value", "data-new"))
			} else {
				write(t, output, string(fresh)+"// hand edit\n")
			}
			before, err := os.ReadFile(output)
			if err != nil {
				t.Fatal(err)
			}
			if err := run(root, true); err == nil {
				t.Fatal("accepted drift")
			}
			after, err := os.ReadFile(output)
			if err != nil || string(before) != string(after) {
				t.Fatal("check rewrote output")
			}
		})
	}
}

func TestInvalidDefinitions(t *testing.T) {
	for _, input := range []string{
		"package", strings.ReplaceAll(synthetic, "HTMLFormElement", "wrong"),
		strings.ReplaceAll(synthetic, "//dom:id", "//dom:unknown"),
		strings.ReplaceAll(synthetic, "Form = \"form\"", "Form = other"),
		strings.ReplaceAll(synthetic, "data-value", "value"),
		strings.ReplaceAll(synthetic, "ChangedDetail struct", "Other struct"),
		strings.ReplaceAll(synthetic, "Count int64", "Count []int"),
	} {
		if _, err := generate([]byte(input)); err == nil {
			t.Errorf("accepted invalid source: %s", input)
		}
	}
}

func TestPayloadNames(t *testing.T) {
	output, err := generate([]byte(synthetic))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(output, `"key": string;`) || strings.Contains(output, `"Key":`) || !strings.Contains(output, `"Text": string;`) {
		t.Fatalf("tagged and untagged names: %s", output)
	}
	for _, tag := range []string{"", "-", ",omitempty"} {
		output, err := generate([]byte(strings.ReplaceAll(synthetic, "key,omitempty", tag)))
		if err != nil || !strings.Contains(output, `"Key": string;`) {
			t.Fatalf("fallback %q: %v: %s", tag, err, output)
		}
	}
	duplicate := strings.ReplaceAll(synthetic, "Text string", "key string")
	if _, err := generate([]byte(duplicate)); err == nil || !strings.Contains(err.Error(), `duplicate TypeScript payload field "key"`) {
		t.Fatalf("duplicate payload names: %v", err)
	}
}

func TestDirectiveAttachment(t *testing.T) {
	if _, err := generate([]byte("package view\n//dom:id HTMLDivElement\nconst ( Undirected = \"undirected\" )")); err == nil || !strings.Contains(err.Error(), "DOM directive on const group") {
		t.Fatalf("group directive must fail clearly: %v", err)
	}
	output, err := generate([]byte("package view\nconst (\nUndirected = \"undirected\"\nDirected = \"directed\" //dom:id HTMLDivElement\n)\n//dom:id HTMLFormElement\nconst Standalone = \"standalone\""))
	if err != nil || strings.Contains(output, "Undirected") || !strings.Contains(output, "getDirected") || !strings.Contains(output, "getStandalone") {
		t.Fatalf("constant comments: %v: %s", err, output)
	}
}

