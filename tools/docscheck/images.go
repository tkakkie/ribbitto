package main

import (
	"fmt"
	"html"
	"net/url"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/yuin/goldmark/ast"
	"github.com/yuin/goldmark/util"
)

const imageLimit = 300 * 1024

func checkImages(root string) ([]string, error) {
	repo, err := os.OpenRoot(root)
	if err != nil {
		return nil, fmt.Errorf("opening repository root: %w", err)
	}
	defer func() { _ = repo.Close() }()
	entries, err := os.ReadDir(filepath.Join(root, "docs/images"))
	if err != nil && !os.IsNotExist(err) {
		return nil, fmt.Errorf("reading images directory: %w", err)
	}
	var problems []string
	for _, entry := range entries {
		if ext := path.Ext(entry.Name()); ext != ".png" && ext != ".webp" {
			continue
		}
		file := "docs/images/" + entry.Name()
		info, err := repo.Lstat(file)
		if err != nil {
			return nil, fmt.Errorf("checking image %s: %w", file, err)
		}
		if info.Mode().IsRegular() && info.Size() > imageLimit {
			problems = append(problems, fmt.Sprintf("%s: %d bytes, over its limit of %d", file, info.Size(), imageLimit))
		}
	}
	files, err := markdownFiles(root)
	if err != nil {
		return nil, fmt.Errorf("listing Markdown files: %w", err)
	}
	for _, file := range files {
		if strings.HasPrefix(file, "docs/schema/") {
			continue // generated by tbls
		}
		source, err := os.ReadFile(filepath.Join(root, file))
		if err != nil {
			return nil, fmt.Errorf("reading document %s: %w", file, err)
		}
		d := parse(source)
		_ = ast.Walk(d.root, func(n ast.Node, entering bool) (ast.WalkStatus, error) {
			image, ok := n.(*ast.Image)
			if !ok || !entering {
				return ast.WalkContinue, nil
			}
			line := d.lineOfNode(image)
			// Empty alt text has no text segment; the containing block
			// still supplies a source position for the diagnostic.
			for parent := image.Parent(); line == 0 && parent != nil; parent = parent.Parent() {
				if parent.Type() == ast.TypeBlock && parent.Lines().Len() > 0 {
					line = d.lineOf(parent.Lines().At(0).Start)
				}
			}
			if problem := imageDestinationProblem(repo, file, string(image.Destination)); problem != "" {
				problems = append(problems, fmt.Sprintf("%s:%d: %s", file, line, problem))
			}
			if strings.TrimSpace(renderedText(image, source)) == "" {
				problems = append(problems, fmt.Sprintf("%s:%d: image has no alt text", file, line))
			}
			return ast.WalkSkipChildren, nil
		})
	}
	sort.Strings(problems)
	return problems, nil
}

func imageDestinationProblem(repo *os.Root, file, destination string) string {
	dest := html.UnescapeString(string(util.UnescapePunctuations([]byte(destination))))
	dest, _, _ = strings.Cut(dest, "#")
	dest, _, _ = strings.Cut(dest, "?")
	if decoded, err := url.PathUnescape(dest); err == nil {
		dest = decoded
	}
	if strings.Contains(dest, "://") || strings.HasPrefix(dest, "mailto:") || strings.HasPrefix(dest, "data:") || strings.HasPrefix(dest, "//") {
		return "external image URL, want a PNG or WebP file in docs/images/"
	}
	// GitHub treats absolute paths as repo-root-relative; our rule requires
	// resolution relative to the containing Markdown file instead.
	if strings.HasPrefix(dest, "/") {
		return "absolute image path, want a relative path to docs/images/"
	}
	// Repository paths use forward slashes on every platform. Normalise
	// before testing the directory so harmless parent components work.
	target := path.Join(path.Dir(file), dest)
	if target == ".." || strings.HasPrefix(target, "../") {
		return target + " escapes repository root, outside docs/images/"
	}
	if path.Dir(target) != "docs/images" {
		return target + " outside docs/images/"
	}
	if ext := path.Ext(target); ext != ".png" && ext != ".webp" {
		return target + " not a PNG or WebP image"
	}
	if info, err := repo.Lstat(target); err != nil || !info.Mode().IsRegular() {
		return target + " does not exist as a regular file"
	}
	return ""
}
