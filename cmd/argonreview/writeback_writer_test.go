func TestWritebackReportEscapes(t *testing.T) {
	report := writebackReport([]writebackEntry{{"bad\nname", nil}}, nil, errors.New("bad\nreason\x1b"))
	if strings.Contains(report, "bad\n") || strings.ContainsRune(report, '\x1b') || !strings.Contains(report, `bad\nname`) {
		t.Fatalf("raw bytes in report: %q", report)
	}
}

func TestWritebackReportKeepsCleanupFailures(t *testing.T) {
	var err error
	for i := range writebackEntryLimit {
		err = errors.Join(err, fmt.Errorf("cleanup %d %s", i, strings.Repeat("x", 200)))
	}
	report := writebackReport(nil, nil, err)
	if strings.Count(report, "refused:") != writebackEntryLimit || !strings.Contains(report, "cleanup 199 ") || len(report) > 50000 {
		t.Fatal("cleanup refusals lost or unbounded")
	}
}
