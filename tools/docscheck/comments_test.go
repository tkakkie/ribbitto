func TestSourceCommentReferences(t *testing.T) {
	for _, tt := range []struct{ name, file, source, want string }{
		{"resolving file", "p/a.go", "// docs/target.md", ""},
		{"resolving anchor", "p/a.go", "// docs/target.md#same-1.", ""},
		{"missing file", "p/a.go", "\n// docs/gone.md", "p/a.go:2: docs/gone.md does not exist"},
		{"missing anchor", "p/a.go", "\n// docs/target.md#gone", "p/a.go:2: docs/target.md has no heading #gone"},
		{"Unicode anchor", "p/a.go", "// docs/target.md#見出し", ""},
		{"non Markdown file", "p/a.go", "// docs/size-exceptions.txt", ""},
		{"missing non Markdown file", "p/a.go", "\n// docs/gone.txt", "p/a.go:2: docs/gone.txt does not exist"},
		{"directory", "p/a.go", "// docs/decisions/", ""},
		{"missing directory", "p/a.go", "\n// docs/gone/", "p/a.go:2: docs/gone does not exist"},
		{"string ignored", "p/a.go", "var x = \"docs/gone.md\"", ""},
		{"comment marker in string ignored", "p/a.go", "var x = \"// docs/gone.md\"", ""},
		{"escaped quote ignored", "p/a.go", "var x = \"\\\" // docs/gone.md\"", ""},
		{"raw multiline string ignored", "p/a.go", "var x = `\n// docs/gone.md\n`", ""},
		{"inline comment after string", "p/a.go", "var x = \"docs/gone.md\" // docs/target.md#gone", "p/a.go:1: docs/target.md has no heading #gone"},
		{"block line numbers", "p/a.go", "/*\n * docs/gone.md\n */", "p/a.go:2: docs/gone.md does not exist"},
		{"block closure", "p/a.go", "/* docs/target.md */ var x = \"docs/gone.md\"", ""},
		{"two block comments", "p/a.go", "/* docs/target.md */ /* docs/gone.md */", "p/a.go:1: docs/gone.md does not exist"},
		{"external URL", "p/a.go", "// https://example.com/docs/gone.md", ""},
		{"non docs reference", "p/a.go", "// other/gone.md", ""},
		{"docscheck fixtures", "tools/docscheck/nested/a.go", "// docs/gone.md", ""},
		{"languagecheck fixtures", "tools/languagecheck/a.go", "// docs/gone.md", ""},
		{"sourcecheck fixtures", "tools/sourcecheck/a.go", "// docs/gone.md", ""},
		{"similar tool name checked", "tools/docschecker/a.go", "// docs/gone.md", "tools/docschecker/a.go:1: docs/gone.md does not exist"},
		{"other tools checked", "tools/other/a.go", "// docs/gone.md", "tools/other/a.go:1: docs/gone.md does not exist"},
		{"vendor", "web/static/vendor/a.js", "// docs/gone.md", ""},
		{"generated Go", "p/a_templ.go", "// Code generated by templ; DO NOT EDIT.\n// docs/gone.md", ""},
		{"generated TypeScript", "web/src/contracts.gen.ts", "// Code generated by domcontract; DO NOT EDIT.\n// docs/gone.md", ""},
		{"generated CSS", "web/static/css/app.css", "/* docs/gone.md */", ""},
		{"build output", "web/static/dist/a.js", "// docs/gone.md", ""},
		{"unsupported file", "p/a.txt", "// docs/gone.md", ""},
		{"node dependency", "node_modules/p/a.js", "// docs/gone.md", ""},
	} {
		t.Run(tt.name, func(t *testing.T) {
			root := repo(t, map[string]string{
				"docs/target.md": "## Same\n## Same\n## 見出し\n", "docs/decisions/a.md": "",
				"docs/size-exceptions.txt": "", tt.file: tt.source,
			})
			problems, err := checkLinks(root)
			if err != nil || strings.Join(problems, "\n") != tt.want {
				t.Fatalf("problems %q, error %v, want %q", problems, err, tt.want)
			}
		})
	}
}

func TestSourceCommentMarkers(t *testing.T) {
	for _, tt := range []struct{ file, source string }{
		{"a.go", "// docs/gone.md"}, {"a.templ", "// docs/gone.md"},
		{"a.ts", "/* docs/gone.md */"}, {"a.js", "// docs/gone.md"}, {"a.mjs", "// docs/gone.md"},
		{"a.css", "/* docs/gone.md */"}, {"a.sql", "-- docs/gone.md"},
		{"b.sql", "/* docs/gone.md */"}, {"Makefile", "# docs/gone.md"},
		{"a.yml", "# docs/gone.md"}, {"a.yaml", "# docs/gone.md"}, {".gitattributes", "# docs/gone.md"},
	} {
		t.Run(tt.file, func(t *testing.T) {
			problems, err := checkLinks(repo(t, map[string]string{tt.file: "\n" + tt.source}))
			want := tt.file + ":2: docs/gone.md does not exist"
			if err != nil || len(problems) != 1 || problems[0] != want {
				t.Fatalf("problems %q, error %v, want %q", problems, err, want)
			}
		})
	}
}

