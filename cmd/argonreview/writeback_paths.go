package main

import (
	"bytes"
	"fmt"
	"strings"
)

// Facts never follow symlinks. A failed lookup refuses rather than inventing absence.
type writebackRepo interface {
	regularFile(rel string) (bool, error)
	directory(rel string) (bool, error)
	trackedAtBase(rel string) (bool, error)
}

func validateWritebackPaths(entries []writebackEntry, repo writebackRepo) error {
	for _, entry := range entries {
		// Keep the copy/guard boundary even if a future allowlist rule is wrong.
		// Do not include its error text: its raw name is not report bounded.
		omit, err := containerCopyPath(entry.name)
		if err != nil || omit {
			return writebackNameError(entry.name, "refused by container copy path boundary")
		}
		parts := strings.Split(entry.name, "/")
		templ, err := writebackTemplPath(parts, repo)
		if err != nil {
			return writebackNameError(entry.name, fmt.Sprintf("checking templ source: %v", err))
		}
		sqlc, err := writebackSQLCPath(parts, repo)
		if err != nil {
			return writebackNameError(entry.name, fmt.Sprintf("checking sqlc source: %v", err))
		}
		var header string
		switch {
		case templ:
			header = "// Code generated by templ - DO NOT EDIT."
		case sqlc:
			header = "// Code generated by sqlc. DO NOT EDIT."
		case len(parts) == 4 && parts[0] == "web" && parts[1] == "static" && parts[2] == "css" && parts[3] == "app.css":
			header = "/*! tailwindcss v"
		default:
			return writebackNameError(entry.name, "outside generated path allowlist")
		}
		// Generator banners catch misplaced output; they are not a security
		// control. A CR is deliberately part of the first line.
		line, _, _ := bytes.Cut(entry.content, []byte{'\n'})
		if header == "/*! tailwindcss v" {
			if strings.HasPrefix(string(line), header) {
				continue
			}
		} else if string(line) == header {
			continue
		}
		return writebackNameError(entry.name, "missing or wrong generator header")
	}
	return nil
}

func writebackTemplPath(parts []string, repo writebackRepo) (bool, error) {
	var dir, file string
	switch {
	case len(parts) == 4 && parts[0] == "internal" && parts[1] == "web" && parts[2] == "view":
		dir, file = "internal/web/view", parts[3]
	case len(parts) == 3 && parts[0] == "internal" && parts[1] == "lintfixture":
		dir, file = "internal/lintfixture", parts[2]
	default:
		return false, nil
	}
	name, ok := strings.CutSuffix(file, "_templ.go")
	if !ok || name == "" {
		return false, nil
	}
	return repo.regularFile(dir + "/" + name + ".templ")
}

func writebackSQLCPath(parts []string, repo writebackRepo) (bool, error) {
	if len(parts) != 6 || parts[0] != "internal" || parts[2] != "internal" || parts[3] != "postgres" || parts[4] != "sqlcgen" {
		return false, nil
	}
	module, file := parts[1], parts[5]
	queries := "db/queries/" + module
	exists, err := repo.directory(queries)
	if err != nil || !exists {
		return false, err
	}
	tracked, err := repo.trackedAtBase("internal/" + module + "/internal/postgres/sqlcgen/doc.go")
	if err != nil || !tracked {
		return false, err
	}
	if file == "db.go" || file == "models.go" {
		return true, nil
	}
	query, ok := strings.CutSuffix(file, ".sql.go")
	if !ok || query == "" {
		return false, nil
	}
	return repo.regularFile(queries + "/" + query + ".sql")
}
