type writebackRepoFixture struct {
	files, directories, tracked map[string]bool
}

func (r writebackRepoFixture) regularFile(rel string) (bool, error)   { return r.files[rel], nil }
func (r writebackRepoFixture) directory(rel string) (bool, error)     { return r.directories[rel], nil }
func (r writebackRepoFixture) trackedAtBase(rel string) (bool, error) { return r.tracked[rel], nil }

func TestWritebackPaths(t *testing.T) {
	const templHeader = "// Code generated by templ - DO NOT EDIT."
	const sqlcHeader = "// Code generated by sqlc. DO NOT EDIT."
	const cssHeader = "/*! tailwindcss v4.1.0 | MIT License */"
	const sqlcDir = "internal/org/internal/postgres/sqlcgen/"
	repo := writebackRepoFixture{
		files: map[string]bool{
			"internal/web/view/x.templ": true, "internal/lintfixture/bad.templ": true,
			"internal/web/other/x.templ": true, "internal/other/view/x.templ": true,
			"internal/lintfixture/internal/x.templ": true, "internal/web/view/sub/x.templ": true,
			"internal/web/view/.templ": true, "internal/web/view/x.go.templ": true,
			"db/queries/org/member.sql": true, "db/queries/org/.sql": true, "db/queries/org/member.go.sql": true,
		},
		directories: map[string]bool{"db/queries/org": true, "db/queries/untracked": true, "db/queries/.git": true},
		tracked: map[string]bool{
			"internal/org/internal/postgres/sqlcgen/doc.go":       true,
			"internal/noqueries/internal/postgres/sqlcgen/doc.go": true,
			"internal/.git/internal/postgres/sqlcgen/doc.go":      true,
		},
	}
	entry := func(name, content string) writebackEntry { return writebackEntry{name, []byte(content)} }
	good := []writebackEntry{entry("internal/web/view/x_templ.go", templHeader+"\npackage view"), entry(sqlcDir+"db.go", sqlcHeader), entry("web/static/css/app.css", cssHeader)}
	for _, tc := range []struct {
		name    string
		entries []writebackEntry
		reason  string
	}{
		{"templ_view", []writebackEntry{good[0]}, ""},
		{"templ_fixture", []writebackEntry{entry("internal/lintfixture/bad_templ.go", templHeader)}, ""},
		{"sqlc_db", []writebackEntry{good[1]}, ""},
		{"sqlc_models", []writebackEntry{entry(sqlcDir+"models.go", sqlcHeader+"\npackage sqlcgen")}, ""},
		{"sqlc_query", []writebackEntry{entry(sqlcDir+"member.sql.go", sqlcHeader)}, ""},
		{"css", []writebackEntry{good[2]}, ""},
		{"several_files", good, ""},
		{"one_bad_among_good", append(append([]writebackEntry{}, good...), entry("AGENTS.md", templHeader)), "copy path"},
		{"workflow", []writebackEntry{entry(".github/workflows/ci.yml", templHeader)}, "copy path"},
		{"instructions", []writebackEntry{entry("AGENTS.md", templHeader)}, "copy path"},
		{"module_file", []writebackEntry{entry("go.mod", templHeader)}, "allowlist"},
		{"missing_templ", []writebackEntry{entry("internal/web/view/missing_templ.go", templHeader)}, "allowlist"},
		{"extra_view_component", []writebackEntry{entry("internal/web/view/x_templ.go/extra", templHeader)}, "allowlist"},
		{"nested_view", []writebackEntry{entry("internal/web/view/sub/x_templ.go", templHeader)}, "allowlist"},
		{"extra_fixture_component", []writebackEntry{entry("internal/lintfixture/bad_templ.go/extra", templHeader)}, "allowlist"},
		{"nested_fixture", []writebackEntry{entry("internal/lintfixture/internal/x_templ.go", templHeader)}, "allowlist"},
		{"wrong_view_root", []writebackEntry{entry("outside/web/view/x_templ.go", templHeader)}, "allowlist"},
		{"wrong_fixture_root", []writebackEntry{entry("outside/lintfixture/bad_templ.go", templHeader)}, "allowlist"},
		{"wrong_fixture_dir", []writebackEntry{entry("internal/other/bad_templ.go", templHeader)}, "allowlist"},
		{"wrong_view_dir", []writebackEntry{entry("internal/web/other/x_templ.go", templHeader)}, "allowlist"},
		{"wrong_module_dir", []writebackEntry{entry("internal/other/view/x_templ.go", templHeader)}, "allowlist"},
		{"empty_templ_name", []writebackEntry{entry("internal/web/view/_templ.go", templHeader)}, "allowlist"},
		{"wrong_templ_suffix", []writebackEntry{entry("internal/web/view/x.go", templHeader)}, "allowlist"},
		{"sqlc_doc", []writebackEntry{entry(sqlcDir+"doc.go", sqlcHeader)}, "allowlist"},
		{"missing_query", []writebackEntry{entry(sqlcDir+"evil.sql.go", sqlcHeader)}, "allowlist"},
		{"new_module", []writebackEntry{entry("internal/newmod/internal/postgres/sqlcgen/db.go", sqlcHeader)}, "allowlist"},
		{"untracked_doc", []writebackEntry{entry("internal/untracked/internal/postgres/sqlcgen/db.go", sqlcHeader)}, "allowlist"},
		{"no_queries_dir", []writebackEntry{entry("internal/noqueries/internal/postgres/sqlcgen/db.go", sqlcHeader)}, "allowlist"},
		{"empty_query", []writebackEntry{entry(sqlcDir+".sql.go", sqlcHeader)}, "allowlist"},
		{"extra_sqlc_component", []writebackEntry{entry(sqlcDir+"db.go/extra", sqlcHeader)}, "allowlist"},
		{"nested_sqlc", []writebackEntry{entry(sqlcDir+"sub/db.go", sqlcHeader)}, "allowlist"},
		{"wrong_sqlc_root", []writebackEntry{entry("outside/org/internal/postgres/sqlcgen/db.go", sqlcHeader)}, "allowlist"},
		{"wrong_sqlc_internal", []writebackEntry{entry("internal/org/outside/postgres/sqlcgen/db.go", sqlcHeader)}, "allowlist"},
		{"wrong_sqlc_postgres", []writebackEntry{entry("internal/org/internal/outside/sqlcgen/db.go", sqlcHeader)}, "allowlist"},
		{"wrong_sqlc_gen", []writebackEntry{entry("internal/org/internal/postgres/outside/db.go", sqlcHeader)}, "allowlist"},
		{"wrong_sqlc_suffix", []writebackEntry{entry(sqlcDir+"member.go", sqlcHeader)}, "allowlist"},
		{"guard_refused_module", []writebackEntry{entry("internal/.git/internal/postgres/sqlcgen/db.go", sqlcHeader)}, "copy path"},
		{"guard_refused_nested", []writebackEntry{entry(sqlcDir+".git/db.go", sqlcHeader)}, "copy path"},
		{"other_css", []writebackEntry{entry("web/static/css/other.css", cssHeader)}, "allowlist"},
		{"extra_css_component", []writebackEntry{entry("web/static/css/app.css/extra", cssHeader)}, "allowlist"},
		{"nested_css", []writebackEntry{entry("web/static/css/sub/app.css", cssHeader)}, "allowlist"},
		{"wrong_css_root", []writebackEntry{entry("outside/static/css/app.css", cssHeader)}, "allowlist"},
		{"wrong_css_leaf_dir", []writebackEntry{entry("web/static/outside/app.css", cssHeader)}, "allowlist"},
		{"wrong_css_dir", []writebackEntry{entry("web/styles/css/app.css", cssHeader)}, "allowlist"},
		{"templ_wrong_header", []writebackEntry{entry(good[0].name, sqlcHeader)}, "generator header"},
		{"sqlc_wrong_header", []writebackEntry{entry(good[1].name, templHeader)}, "generator header"},
		{"css_wrong_header", []writebackEntry{entry(good[2].name, templHeader)}, "generator header"},
		{"missing_header", []writebackEntry{entry(good[0].name, "")}, "generator header"},
		{"templ_CR", []writebackEntry{entry(good[0].name, templHeader+"\r\n")}, "generator header"},
		{"sqlc_CR", []writebackEntry{entry(good[1].name, sqlcHeader+"\r\n")}, "generator header"},
		{"sqlc_extra_text", []writebackEntry{entry(good[1].name, sqlcHeader+" extra")}, "generator header"},
		{"templ_extra_text", []writebackEntry{entry(good[0].name, templHeader+" extra")}, "generator header"},
		{"header_on_second_line", []writebackEntry{entry(good[1].name, "\n"+sqlcHeader)}, "generator header"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			err := validateWritebackPaths(tc.entries, repo)
			if tc.reason == "" {
				if err != nil {
					t.Fatal(err)
				}
				return
			}
			if err == nil || !strings.Contains(err.Error(), tc.reason) {
				t.Fatalf("want refusal %q, got %v", tc.reason, err)
			}
			bad := tc.entries[len(tc.entries)-1].name
			if !strings.Contains(err.Error(), writebackQuotedName(bad)) {
				t.Fatalf("report lost entry name: %v", err)
			}
		})
	}
}

func TestWritebackTemplSource(t *testing.T) {
	const source = "internal/web/view/x.templ"
	entries := []writebackEntry{{"internal/web/view/x_templ.go", []byte("// Code generated by templ - DO NOT EDIT.")}}
	for _, tc := range []struct {
		name   string
		repo   writebackRepoFixture
		accept bool
	}{
		{"regular_file", writebackRepoFixture{files: map[string]bool{source: true}}, true},
		{"missing_x_templ", writebackRepoFixture{}, false},
		{"directory_is_not_regular", writebackRepoFixture{directories: map[string]bool{source: true}}, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			err := validateWritebackPaths(entries, tc.repo)
			if (err == nil) != tc.accept {
				t.Fatalf("accept %v, error %v", tc.accept, err)
			}
		})
	}
}
