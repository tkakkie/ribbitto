func TestWritebackRepoBaseline(t *testing.T) {
	for _, format := range []string{"sha1", "sha256"} {
		t.Run(format, func(t *testing.T) {
			tree := writebackFixture(t, format)
			// The merge base, not HEAD, controls the baseline and module provenance.
			write(t, filepath.Join(tree, "new"), "new commit")
			writebackGitT(t, tree, "add", "new")
			writebackGitT(t, tree, "commit", "--quiet", "-m", "head")
			for _, key := range []string{"GIT_DIR", "GIT_WORK_TREE", "GIT_CONFIG_COUNT", "GIT_CONFIG_PARAMETERS", "GIT_REPLACE_REF_BASE"} {
				t.Setenv(key, "hostile")
			}
			r := writebackRepoT(t, tree)
			if r.format != format || r.base == writebackGitT(t, tree, "rev-parse", "HEAD") {
				t.Fatal("wrong baseline")
			}
			if found, err := r.trackedAtBase(writebackSQL + "doc.go"); err != nil || !found {
				t.Fatalf("tracked: %v, %v", found, err)
			}
			if found, err := r.trackedAtBase(writebackSQL + "absent.go"); err != nil || found {
				t.Fatalf("absent: %v, %v", found, err)
			}
			write(t, filepath.Join(tree, "sqlc.yaml"), "changed HEAD configuration")
			writebackGitT(t, tree, "add", "sqlc.yaml")
			writebackGitT(t, tree, "commit", "--quiet", "-m", "changed")
			if _, err := prepareWritebackRepo(context.Background(), tree); err == nil || !strings.Contains(err.Error(), "sqlc.yaml differs") {
				t.Fatalf("HEAD accepted over merge base: %v", err)
			}
		})
	}
}

func TestWritebackRepoFacts(t *testing.T) {
	tree := writebackFixture(t, "sha1")
	r := writebackRepoT(t, tree)
	symlink(t, filepath.Join(tree, "sqlc.yaml"), filepath.Join(tree, "file-link"))
	symlink(t, filepath.Join(tree, "db"), filepath.Join(tree, "dir-link"))
	for _, tc := range []struct {
		name                  string
		directory, want, fail bool
	}{
		{"sqlc.yaml", false, true, false}, {"db", true, true, false}, {"missing", false, false, false}, {"missing/child", true, false, false},
		{"file-link", false, false, false}, {"dir-link", true, false, false}, {"dir-link/queries", true, false, true}, {"sqlc.yaml/child", false, false, true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			var found bool
			var err error
			if tc.directory {
				found, err = r.directory(tc.name)
			} else {
				found, err = r.regularFile(tc.name)
			}
			if found != tc.want || (err != nil) != tc.fail {
				t.Fatalf("fact %v, %v", found, err)
			}
		})
	}
	// A symlink blob at the merge base cannot establish a module.
	writebackGitT(t, tree, "update-index", "--cacheinfo", "120000,"+implementBlobOID([]byte("elsewhere"), "sha1")+","+writebackSQL+"doc.go")
	// Write the object explicitly: no external process/filter may choose its bytes.
	cmd := containerGit(context.Background(), tree, "hash-object", "-w", "--stdin")
	cmd.Stdin = strings.NewReader("elsewhere")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("object: %s, %v", out, err)
	}
	writebackGitT(t, tree, "commit", "--quiet", "-m", "symlink mode")
	r.base = writebackGitT(t, tree, "rev-parse", "HEAD")
	if _, err := r.trackedAtBase(writebackSQL + "doc.go"); err == nil {
		t.Fatal("non-regular baseline blob accepted")
	}
	write(t, filepath.Join(tree, ".git/config"), "[broken")
	if _, err := r.trackedAtBase(writebackSQL + "doc.go"); err == nil {
		t.Fatal("Git failure became absence")
	}
}

type writebackFaultRepo struct {
	writebackRepoFixture
	fail string
}

func (r writebackFaultRepo) regularFile(rel string) (bool, error) {
	if r.fail == "file" {
		return false, errors.New("file fact failed")
	}
	return true, nil
}
func (r writebackFaultRepo) directory(rel string) (bool, error) {
	if r.fail == "directory" {
		return false, errors.New("directory fact failed")
	}
	return true, nil
}
func (r writebackFaultRepo) trackedAtBase(rel string) (bool, error) {
	if r.fail == "tracked" {
		return false, errors.New("tracked fact failed")
	}
	return true, nil
}

func TestWritebackFactErrorsRefuse(t *testing.T) {
	for _, fail := range []string{"file", "directory", "tracked"} {
		name, banner := writebackX, writebackBanner
		if fail != "file" {
			name, banner = writebackSQL+"db.go", "// Code generated by sqlc. DO NOT EDIT."
		}
		err := validateWritebackPaths([]writebackEntry{{name, []byte(banner)}}, writebackFaultRepo{fail: fail})
		if err == nil || !strings.Contains(err.Error(), fail+" fact failed") {
			t.Fatalf("fact error hidden: %v", err)
		}
	}
}

func TestWritebackRootSwap(t *testing.T) {
	tree := writebackFixture(t, "sha1")
	r := writebackRepoT(t, tree)
	hook := func(stage, _ string) {
		if stage == "after-validation" {
			if err := os.Rename(tree, tree+".old"); err != nil {
				t.Fatal(err)
			}
			t.Cleanup(func() { _ = os.RemoveAll(tree + ".old") })
			mkdir(t, tree)
		}
	}
	report, err := writebackFiles(tree, r.root, []writebackEntry{{writebackX, []byte(writebackBanner)}}, r, hook)
	if err == nil || !strings.Contains(report, "0 written") {
		t.Fatalf("root swap: %s, %v", report, err)
	}
	writebackContentT(t, tree+".old", writebackX, "old x")
	writebackNoTempsT(t, tree+".old")
}
