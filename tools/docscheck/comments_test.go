func TestSourceCommentQuoteNewline(t *testing.T) {
	for _, tt := range []struct{ file, source, comment string }{
		{"a.go", "var x = '\"", "//"}, {"a.sql", "SELECT 'x", "--"},
		{"a.yml", "name: Don't fail", "#"}, {"Makefile", "\techo don't", "#"},
		{"a.templ", "<p>Don't</p>", "//"}, {"a.css", "a { content: \"x", "/*"},
		{"a.ts", `s.replace(/'/g, "&#39;")`, "//"}, {"a.js", `s.replace(/"/g, '')`, "//"},
	} {
		t.Run(tt.file, func(t *testing.T) {
			root := repo(t, map[string]string{tt.file: tt.source + "\n" + tt.comment + " docs/gone.md"})
			problems, err := checkLinks(root)
			if err != nil || strings.Join(problems, "\n") != tt.file+":2: docs/gone.md does not exist" {
				t.Fatalf("problems %q, error %v", problems, err)
			}
		})
	}
}

func TestSourceCommentTrackedFiles(t *testing.T) {
	root := repo(t, map[string]string{"a.go": "// docs/gone.md"})
	if err := os.MkdirAll(filepath.Join(root, "web/static/.dist-leftover"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Rename(filepath.Join(root, "a.go"), filepath.Join(root, "web/static/.dist-leftover/a.go")); err != nil {
		t.Fatal(err)
	}
	if err := walkSourceComments(root, func(string, line) {}); err == nil {
		t.Fatal("missing tracked source must fail")
	}
	policyGit(t, root, "rm", "a.go")
	if err := walkSourceComments(root, func(path string, l line) { t.Errorf("untracked comment: %s:%d", path, l.number) }); err != nil {
		t.Fatal(err)
	}
	if err := walkSourceComments(t.TempDir(), func(string, line) {}); err == nil {
		t.Fatal("unreadable git index must fail")
	}
}

func TestSourceCommentMarkers(t *testing.T) {
	for _, tt := range []struct{ file, source string }{
		{"a.go", "// docs/gone.md"}, {"a.templ", "// docs/gone.md"},
		{"a.ts", "/* docs/gone.md */"}, {"a.js", "// docs/gone.md"}, {"a.mjs", "// docs/gone.md"},
		{"a.css", "/* docs/gone.md */"}, {"a.sql", "-- docs/gone.md"},
		{"b.sql", "/* docs/gone.md */"}, {"Makefile", "# docs/gone.md"},
		{"a.yml", "# docs/gone.md"}, {"a.yaml", "# docs/gone.md"}, {".gitattributes", "# docs/gone.md"},
	} {
		t.Run(tt.file, func(t *testing.T) {
			problems, err := checkLinks(repo(t, map[string]string{tt.file: "\n" + tt.source}))
			want := tt.file + ":2: docs/gone.md does not exist"
			if err != nil || len(problems) != 1 || problems[0] != want {
				t.Fatalf("problems %q, error %v, want %q", problems, err, want)
			}
		})
	}
}

