const writebackX = "internal/web/view/x_templ.go"
const writebackY = "internal/web/view/y_templ.go"
const writebackSQL = "internal/org/internal/postgres/sqlcgen/"
const writebackBanner = "// Code generated by templ - DO NOT EDIT.\n"

func writebackGitT(t *testing.T, tree string, args ...string) string {
	t.Helper()
	cmd := containerGit(context.Background(), tree, append([]string{"-c", "user.name=t", "-c", "user.email=t@example.invalid"}, args...)...)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v %s", args, err, out)
	}
	return strings.TrimSpace(string(out))
}

func writebackFixture(t *testing.T, format string) string {
	t.Helper()
	tree := resolved(t, t.TempDir())
	writebackGitT(t, tree, "init", "--quiet", "--template=", "--object-format="+format)
	for name, content := range map[string]string{
		"go.mod":       "module example.invalid/check\n\ngo 1.27.3\n",
		"tools/go.mod": "require github.com/a-h/templ v0.3.1070\nrequire github.com/sqlc-dev/sqlc v1.31.1\n",
		"sqlc.yaml":    "version: 2\n", "internal/web/view/x.templ": "package view", "internal/web/view/y.templ": "package view",
		writebackX: "old x", writebackY: "old y", "web/static/css/app.css": "old css",
		"db/queries/org/member.sql": "select 1;", writebackSQL + "doc.go": "package sqlcgen",
		writebackSQL + "db.go": "old db", writebackSQL + "models.go": "old models",
	} {
		write(t, filepath.Join(tree, name), content)
	}
	writebackGitT(t, tree, "add", "-A")
	writebackGitT(t, tree, "commit", "--quiet", "-m", "baseline")
	writebackGitT(t, tree, "update-ref", "refs/remotes/origin/main", "HEAD")
	return tree
}

func writebackRepoT(t *testing.T, tree string) *diskWritebackRepo {
	t.Helper()
	r, err := prepareWritebackRepo(context.Background(), tree)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { closeFD(r.root) })
	return r
}
func writebackContentT(t *testing.T, tree, name, want string) {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(tree, name))
	if err != nil || string(data) != want {
		t.Fatalf("%q: got %q, %v; want %q", name, data, err, want)
	}
}
func writebackNoTempsT(t *testing.T, tree string) {
	t.Helper()
	if err := filepath.WalkDir(tree, func(p string, d fs.DirEntry, err error) error {
		if err == nil && strings.HasPrefix(d.Name(), ".argonreview-writeback-") {
			t.Errorf("temporary file left: %s", p)
		}
		return err
	}); err != nil {
		t.Fatal(err)
	}
}

func TestWritebackWriterRefusals(t *testing.T) {
	for _, kind := range []string{"symlink", "parent symlink", "hard link", "FIFO", "directory", "oversized", "missing parent", "missing db", "missing models", "missing css", "outside allowlist", "wrong banner"} {
		t.Run(kind, func(t *testing.T) {
			tree := writebackFixture(t, "sha1")
			repo := writebackRepoT(t, tree)
			entries := []writebackEntry{{writebackX, []byte(writebackBanner + "new x")}, {writebackY, []byte(writebackBanner + "new y")}}
			dest := filepath.Join(tree, writebackY)
			switch kind {
			case "outside allowlist":
				entries = append(entries, writebackEntry{"web/static/css/other.css", []byte("/*! tailwindcss v4")})
			case "wrong banner":
				entries[1].content = []byte("wrong")
			case "missing db", "missing models", "missing css":
				name := writebackSQL + "db.go"
				if kind == "missing models" {
					name = writebackSQL + "models.go"
				}
				if kind == "missing css" {
					name = "web/static/css/app.css"
				}
				if err := os.Remove(filepath.Join(tree, name)); err != nil {
					t.Fatal(err)
				}
				banner := "// Code generated by sqlc. DO NOT EDIT.\n"
				if kind == "missing css" {
					banner = "/*! tailwindcss v4 */"
				}
				entries[1] = writebackEntry{name, []byte(banner)}
			case "parent symlink", "missing parent":
				parent := filepath.Join(tree, "internal/web/view")
				outside := filepath.Join(resolved(t, t.TempDir()), "view")
				if err := os.Rename(parent, outside); err != nil {
					t.Fatal(err)
				}
				if kind == "parent symlink" {
					symlink(t, outside, parent)
				}
			default:
				if err := os.Remove(dest); err != nil {
					t.Fatal(err)
				}
				switch kind {
				case "symlink":
					symlink(t, filepath.Join(tree, writebackX), dest)
				case "hard link":
					if err := os.Link(filepath.Join(tree, writebackX), dest); err != nil {
						t.Fatal(err)
					}
				case "FIFO":
					if err := syscall.Mkfifo(dest, 0o600); err != nil {
						t.Fatal(err)
					}
				case "directory":
					mkdir(t, dest)
				case "oversized":
					write(t, dest, "")
					if err := os.Truncate(dest, writebackFileLimit+1); err != nil {
						t.Fatal(err)
					}
				}
			}
			report, err := writebackFiles(tree, repo.root, entries, repo, nil)
			if err == nil || !strings.Contains(report, "0 written") || !strings.Contains(report, "refused:") {
				t.Fatalf("accepted %s: %s, %v", kind, report, err)
			}
			if kind != "parent symlink" && kind != "missing parent" {
				writebackContentT(t, tree, writebackX, "old x")
			}
			writebackNoTempsT(t, tree)
		})
	}
}

func TestWritebackWriterSuccess(t *testing.T) {
	tree := writebackFixture(t, "sha1")
	repo := writebackRepoT(t, tree)
	entries := []writebackEntry{{writebackX, []byte(writebackBanner + "new")}, {writebackY, []byte("old y")}}
	// The equal fixture must still carry a valid banner.
	write(t, filepath.Join(tree, writebackY), writebackBanner+"same")
	identical, err := os.Stat(filepath.Join(tree, writebackY))
	if err != nil {
		t.Fatal(err)
	}
	entries[1].content = []byte(writebackBanner + "same")
	write(t, filepath.Join(tree, "internal/web/view/sp ace.templ"), "package view")
	entries = append(entries, writebackEntry{"internal/web/view/sp ace_templ.go", []byte(writebackBanner + "new file")}, writebackEntry{writebackSQL + "member.sql.go", []byte("// Code generated by sqlc. DO NOT EDIT.\nnew query")})
	// The fixture's archive mode is 0600. The writer cannot inherit it.
	parsed, err := parseWritebackArchive(strings.NewReader(string(writebackTestArchive(t, entries, tar.FormatUSTAR, nil))))
	if err != nil {
		t.Fatal(err)
	}
	report, err := writebackFiles(tree, repo.root, parsed, repo, nil)
	if err != nil || !strings.Contains(report, "3 written, 1 identical") || !strings.Contains(report, fmt.Sprintf("sha256 %x -> %x", sha256.Sum256([]byte("old x")), sha256.Sum256(entries[0].content))) || !strings.Contains(report, "sha256 absent ->") {
		t.Fatalf("report: %s, %v", report, err)
	}
	for _, e := range entries {
		writebackContentT(t, tree, e.name, string(e.content))
		info, err := os.Stat(filepath.Join(tree, e.name))
		if err != nil {
			t.Fatal(err)
		}
		if e.name == writebackY {
			if !os.SameFile(identical, info) || !info.ModTime().Equal(identical.ModTime()) {
				t.Fatal("identical file touched")
			}
		} else if info.Mode().Perm() != 0o644 {
			t.Fatalf("mode %o", info.Mode())
		}
	}
	report, err = writebackFiles(tree, repo.root, entries, repo, nil)
	if err != nil || !strings.Contains(report, "0 written, 4 identical") {
		t.Fatalf("retry: %s, %v", report, err)
	}
	writebackNoTempsT(t, tree)
}

func TestWritebackWriterRaces(t *testing.T) {
	for _, kind := range []string{"first symlink", "second symlink", "same bytes new inode", "mtime", "hard link", "absent appeared", "parent swap", "temp failure", "cleanup failure"} {
		t.Run(kind, func(t *testing.T) {
			tree := writebackFixture(t, "sha1")
			repo := writebackRepoT(t, tree)
			outside := filepath.Join(resolved(t, t.TempDir()), "outside")
			write(t, outside, "outside unchanged")
			entries := []writebackEntry{{writebackX, []byte(writebackBanner + "new x")}, {writebackY, []byte(writebackBanner + "new y")}}
			if kind == "temp failure" {
				entries[1] = writebackEntry{"web/static/css/app.css", []byte("/*! tailwindcss v4 */")}
			}
			if kind == "absent appeared" {
				if err := os.Remove(filepath.Join(tree, writebackX)); err != nil {
					t.Fatal(err)
				}
			}
			hook := func(stage, name string) {
				if kind == "temp failure" {
					if stage == "before-temp" && name == "web/static/css/app.css" {
						// First temp is ready, but a failed second preparation must replace none.
						if err := os.Chmod(filepath.Join(tree, "web/static/css"), 0o500); err != nil {
							t.Fatal(err)
						}
						t.Cleanup(func() { _ = os.Chmod(filepath.Join(tree, "web/static/css"), 0o700) })
					}
					return
				}
				target := writebackX
				if kind == "second symlink" {
					target = writebackY
				}
				if stage != "before-rename" || name != target {
					return
				}
				p := filepath.Join(tree, target)
				switch kind {
				case "first symlink", "second symlink":
					if err := os.Remove(p); err != nil {
						t.Fatal(err)
					}
					symlink(t, outside, p)
				case "same bytes new inode":
					write(t, p+".new", "old x")
					if err := os.Rename(p+".new", p); err != nil {
						t.Fatal(err)
					}
				case "mtime":
					st, err := os.Stat(p)
					if err != nil {
						t.Fatal(err)
					}
					if err := os.Chtimes(p, st.ModTime(), st.ModTime().Add(1e9)); err != nil {
						t.Fatal(err)
					}
				case "hard link":
					if err := os.Link(p, outside+".link"); err != nil {
						t.Fatal(err)
					}
				case "absent appeared":
					write(t, p, "appeared")
				case "cleanup failure":
					if err := os.Chmod(filepath.Dir(p), 0o500); err != nil {
						t.Fatal(err)
					}
					t.Cleanup(func() { _ = os.Chmod(filepath.Dir(p), 0o700) })
				case "parent swap":
					parent := filepath.Dir(p)
					if err := os.Rename(parent, parent+".old"); err != nil {
						t.Fatal(err)
					}
					symlink(t, filepath.Dir(outside), parent)
				}
			}
			report, err := writebackFiles(tree, repo.root, entries, repo, hook)
			if err == nil {
				t.Fatalf("race accepted: %s", report)
			}
			want := "0 written"
			if kind == "second symlink" {
				want = "1 written"
				writebackContentT(t, tree, writebackX, writebackBanner+"new x")
			}
			if !strings.Contains(report, want) || !strings.Contains(report, "not replaced") {
				t.Fatalf("partial report: %s", report)
			}
			writebackContentT(t, filepath.Dir(outside), "outside", "outside unchanged")
			if kind == "temp failure" {
				if err := os.Chmod(filepath.Join(tree, "web/static/css"), 0o700); err != nil {
					t.Fatal(err)
				}
			}
			if kind == "cleanup failure" {
				if !strings.Contains(report, "cannot remove temporary file") || !strings.Contains(report, ".argonreview-writeback-") {
					t.Fatalf("cleanup failure lost: %s", report)
				}
				if err := os.Chmod(filepath.Join(tree, "internal/web/view"), 0o700); err != nil {
					t.Fatal(err)
				}
				names, err := filepath.Glob(filepath.Join(tree, "internal/web/view/.argonreview-writeback-*"))
				if err != nil {
					t.Fatal(err)
				}
				for _, p := range names {
					if err := os.Remove(p); err != nil {
						t.Fatal(err)
					}
				}
			}
			writebackNoTempsT(t, tree)
		})
	}
}

func TestWritebackNoFollowOpens(t *testing.T) {
	tree := writebackFixture(t, "sha1")
	repo := writebackRepoT(t, tree)
	outside := resolved(t, t.TempDir())
	symlink(t, outside, filepath.Join(tree, "linked"))
	if fd, err := openWritebackParent(repo.root, "linked/file"); err == nil {
		closeFD(fd)
		t.Fatal("parent open followed symlink")
	}
	hook := func(stage, name string) {
		if stage == "before-destination-open" {
			p := filepath.Join(tree, name)
			if err := os.Remove(p); err != nil {
				t.Fatal(err)
			}
			symlink(t, filepath.Join(tree, writebackY), p)
		}
	}
	_, err := writebackFiles(tree, repo.root, []writebackEntry{{writebackX, []byte(writebackBanner)}}, repo, hook)
	// Require the open itself to refuse; a later stat mismatch is insufficient.
	if err == nil || !strings.Contains(err.Error(), "opening destination") {
		t.Fatalf("destination open did not refuse link: %v", err)
	}
}

