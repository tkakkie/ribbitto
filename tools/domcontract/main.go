// Command domcontract reads Go definitions with go/parser, never importing an
// application package: tools is a separate module. -check compares without writing.
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

func main() {
	check := flag.Bool("check", false, "fail on missing or stale contracts without writing")
	flag.Parse()
	if flag.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "usage: domcontract [-check] <repository root>")
		os.Exit(2)
	}
	if err := run(flag.Arg(0), *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(root string, check bool) error {
	source, err := os.ReadFile(filepath.Join(root, "internal/web/view/contracts.go"))
	if err != nil {
		return fmt.Errorf("reading DOM definitions: %w", err)
	}
	output, err := generate(source)
	if err != nil {
		return err
	}
	path := filepath.Join(root, "web/src/contracts.gen.ts")
	if check {
		old, err := os.ReadFile(path)
		if err != nil || string(old) != output {
			return fmt.Errorf("%s is missing or stale: run go generate ./internal/web/view", path)
		}
		return nil
	}
	if err := os.WriteFile(path, []byte(output), 0644); err != nil {
		return fmt.Errorf("writing DOM contract: %w", err)
	}
	return nil
}

func generate(source []byte) (string, error) {
	file, err := parser.ParseFile(token.NewFileSet(), "contracts.go", source, parser.ParseComments)
	if err != nil {
		return "", fmt.Errorf("parsing DOM definitions: %w", err)
	}
	var out strings.Builder
	out.WriteString("// Code generated by domcontract; DO NOT EDIT.\n\n")
	var attributes []string
	for _, decl := range file.Decls {
		group, ok := decl.(*ast.GenDecl)
		if !ok || group.Tok != token.CONST {
			continue
		}
		for _, spec := range group.Specs {
			value := spec.(*ast.ValueSpec)
			doc := value.Doc
			if doc == nil {
				doc = group.Doc
			}
			if doc == nil {
				continue
			}
			for _, comment := range doc.List {
				directive, ok := strings.CutPrefix(comment.Text, "//dom:")
				if !ok {
					continue
				}
				parts := strings.Fields(directive)
				if len(parts) == 0 || len(value.Names) != 1 || len(value.Values) != 1 {
					return "", fmt.Errorf("invalid DOM definition")
				}
				name := value.Names[0].Name
				literal, ok := value.Values[0].(*ast.BasicLit)
				if !ok || literal.Kind != token.STRING {
					return "", fmt.Errorf("%s must be a string literal", name)
				}
				text, err := strconv.Unquote(literal.Value)
				if err != nil {
					return "", fmt.Errorf("reading %s: %w", name, err)
				}
				fmt.Fprintf(&out, "export const %s = %q;\n", name, text)
				switch parts[0] {
				case "id", "suffix":
					if len(parts) != 2 || !strings.HasPrefix(parts[1], "HTML") || !strings.HasSuffix(parts[1], "Element") {
						return "", fmt.Errorf("%s needs a DOM element type", name)
					}
					args, id := "", name
					if parts[0] == "suffix" {
						args = "suffix: string"
						fmt.Fprintf(&out, "export const %sID = (%s): string => %s + suffix;\n", name, args, name)
						id = name + "ID(suffix)"
					}
					fmt.Fprintf(&out, "export const %sSelector = (%s): string => \"#\" + %s;\n", name, args, id)
					call := ""
					if args != "" {
						args += ", "
						call = "suffix"
					}
					fmt.Fprintf(&out, "export const get%s = (%sroot: ParentNode = document): %s | null => root.querySelector<%s>(%sSelector(%s));\n\n", name, args, parts[1], parts[1], name, call)
				case "attribute":
					if len(parts) != 1 || !strings.HasPrefix(text, "data-") {
						return "", fmt.Errorf("invalid attribute %s", name)
					}
					attributes = append(attributes, "typeof "+name)
				case "event":
					if len(parts) != 2 {
						return "", fmt.Errorf("%s needs a payload struct", name)
					}
					payload, err := payloadType(file, parts[1])
					if err != nil {
						return "", err
					}
					fmt.Fprintf(&out, "export type %s = %s;\n", parts[1], payload)
					fmt.Fprintf(&out, "export function dispatch%s(target: EventTarget, detail: %s): boolean {\n  return target.dispatchEvent(new CustomEvent(%s, { detail }));\n}\n", name, parts[1], name)
					fmt.Fprintf(&out, "export function listen%s(target: EventTarget, listener: (detail: %s) => void): () => void {\n  const handle = (event: Event): void => listener((event as CustomEvent<%s>).detail);\n  target.addEventListener(%s, handle);\n  return () => target.removeEventListener(%s, handle);\n}\n\n", name, parts[1], parts[1], name, name)
				default:
					return "", fmt.Errorf("unknown DOM kind %q", parts[0])
				}
			}
		}
	}
	if len(attributes) > 0 {
		fmt.Fprintf(&out, "\nexport type ContractAttribute = %s;\n", strings.Join(attributes, " | "))
		out.WriteString("export const readAttribute = (element: Element, name: ContractAttribute): string | null => element.getAttribute(name);\nexport const writeAttribute = (element: Element, name: ContractAttribute, value: string): void => element.setAttribute(name, value);\n")
	}
	return out.String(), nil
}

func payloadType(file *ast.File, name string) (string, error) {
	for _, decl := range file.Decls {
		group, ok := decl.(*ast.GenDecl)
		if !ok || group.Tok != token.TYPE {
			continue
		}
		for _, spec := range group.Specs {
			spec := spec.(*ast.TypeSpec)
			if spec.Name.Name != name {
				continue
			}
			fields, ok := spec.Type.(*ast.StructType)
			if !ok {
				return "", fmt.Errorf("%s must be a payload struct", name)
			}
			if len(fields.Fields.List) == 0 {
				return "Record<string, never>", nil
			}
			var out strings.Builder
			out.WriteString("{")
			for _, field := range fields.Fields.List {
				kind, ok := field.Type.(*ast.Ident)
				if !ok || len(field.Names) == 0 {
					return "", fmt.Errorf("unsupported payload field in %s", name)
				}
				types := map[string]string{"string": "string", "bool": "boolean", "int": "number", "int64": "number", "float64": "number"}
				ts, ok := types[kind.Name]
				if !ok {
					return "", fmt.Errorf("unsupported payload type %s", kind.Name)
				}
				for _, fieldName := range field.Names {
					fmt.Fprintf(&out, " %s: %s;", fieldName.Name, ts)
				}
			}
			out.WriteString(" }")
			return out.String(), nil
		}
	}
	return "", fmt.Errorf("missing payload struct %s", name)
}
